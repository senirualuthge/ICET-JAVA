    private void btnAddBatchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddBatchActionPerformed
        String batchNo = txtBatchNo.getText().trim();
        if (batchNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Batch number could not be generated");
            return;
        }
        if (AccessBatchCollection.getInstance().getBatchCollection().searchBatch(batchNo) != null) {
            JOptionPane.showMessageDialog(this, "This batch is already added in the system");
            return;
        }
        int status = cmbStatus.getSelectedIndex() == 1 ? Batch.STATUS_CLOSED : Batch.STATUS_OPEN;
        boolean isAdded = AccessBatchCollection.getInstance().getBatchCollection().addNewBatch(new Batch(batchNo, status));
        if (isAdded) {
            JOptionPane.showMessageDialog(this, "Batch " + batchNo + " added successfully");
            txtBatchNo.setText(AccessBatchCollection.getInstance().getBatchCollection().generateNextBatchNo());
            cmbStatus.setSelectedIndex(0);
        } else {
            JOptionPane.showMessageDialog(this, "Add Batch Fail");
        }
    }//GEN-LAST:event_btnAddBatchActionPerformed

