    /**
     * Builds one "xxx Batch" button per batch and stacks them vertically.
     */
    private void loadBatchButtons() {
        jPanelButtons.setLayout(new javax.swing.BoxLayout(jPanelButtons, javax.swing.BoxLayout.PAGE_AXIS));
        Batch[] batches = AccessBatchCollection.getInstance().getBatchCollection().getAllBatch();
        for (Batch batch : batches) {
            javax.swing.JButton btnBatch = new javax.swing.JButton(batch.getBatchNo() + " Batch");
            btnBatch.setFont(new java.awt.Font("Segoe UI", 1, 14)); // NOI18N
            btnBatch.setActionCommand(batch.getBatchNo());
            btnBatch.setAlignmentX(java.awt.Component.CENTER_ALIGNMENT);
            btnBatch.setMaximumSize(new java.awt.Dimension(220, 34));
            btnBatch.addActionListener(new java.awt.event.ActionListener() {
                public void actionPerformed(java.awt.event.ActionEvent evt) {
                    btnBatchActionPerformed(evt);
                }
            });
            jPanelButtons.add(btnBatch);
            jPanelButtons.add(javax.swing.Box.createVerticalStrut(12));
        }
    }

