    private void loadReport() {
        DefaultTableModel dtm = (DefaultTableModel) tblReport.getModel();
        dtm.setRowCount(0);
        Student[] students = AccessStudentCollection.getInstance().getStudentCollection().getAllStudentSortedByName();
        for (Student student : students) {
            Object[] rowData = {
                student.getBatchNo(),
                student.getRegistrationNo(),
                Student.marksText(student.getPrfMarks()),
                Student.marksText(student.getDbmsMarks()),
                student.getGpaText()
            };
            dtm.addRow(rowData);
        }
    }

