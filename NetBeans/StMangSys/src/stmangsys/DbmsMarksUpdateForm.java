    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String marksText = txtNewMarks.getText().trim();
        if (marksText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the new DBMS marks");
            return;
        }
        int marks;
        try {
            marks = Integer.parseInt(marksText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Marks must be a number (-1 for absent, or 0 - 100)");
            return;
        }
        if (marks == Student.MARK_ABSENT) {
            int choice = JOptionPane.showConfirmDialog(this,
                    "Mark the student as ABSENT for DBMS?",
                    "Confirm Absent", JOptionPane.YES_NO_OPTION);
            if (choice != JOptionPane.YES_OPTION) {
                return;
            }
        } else if (!Student.isRealMark(marks)) {
            JOptionPane.showMessageDialog(this, "Marks must be within the range of 0 to 100 (or -1 for absent)");
            return;
        }
        boolean isUpdated = AccessStudentCollection.getInstance().getStudentCollection()
                .updateDbmsMarks(currentRegistrationNo, marks);
        if (isUpdated) {
            JOptionPane.showMessageDialog(this, "Student Marks Successfully Updated!");
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "This student does not exist in the system");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

