    private void loadTable() {
        DefaultTableModel dtm = (DefaultTableModel) tblBatches.getModel();
        dtm.setRowCount(0);
        Batch[] batches = AccessBatchCollection.getInstance().getBatchCollection().getAllBatch();
        for (int i = 0; i < batches.length; i++) {
            Object[] rowData = {
                String.valueOf(i + 1),
                batches[i].getBatchNo(),
                String.valueOf(AccessBatchCollection.getInstance().getBatchCollection().getStudentCount(batches[i].getBatchNo())),
                batches[i].getStatusText()
            };
            dtm.addRow(rowData);
        }
    }

