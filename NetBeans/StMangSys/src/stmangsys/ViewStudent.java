    private void searchAndPopulate() {
        String regNo = txtRegNo.getText().trim();
        if (regNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Registration No");
            return;
        }
        Student student = AccessStudentCollection.getInstance().getStudentCollection().searchStudent(regNo);
        if (student == null) {
            JOptionPane.showMessageDialog(this, "This student does not exist in the system");
            return;
        }
        txtRegNo.setText(student.getRegistrationNo());
        txtName.setText(student.getName());
        txtNic.setText(student.getNic());
        txtPrfMarks.setText(Student.marksText(student.getPrfMarks()));
        txtDbmsMarks.setText(Student.marksText(student.getDbmsMarks()));
        txtGpa.setText(student.getGpaText());
    }

