    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (currentBatchNo == null) {
            JOptionPane.showMessageDialog(this, "Please search a batch first");
            return;
        }
        int status = cmbStatus.getSelectedIndex() == 1 ? Batch.STATUS_CLOSED : Batch.STATUS_OPEN;
        boolean isUpdated = AccessBatchCollection.getInstance().getBatchCollection()
                .updateBatchStatus(currentBatchNo, status);
        if (isUpdated) {
            JOptionPane.showMessageDialog(this, "Batch status successfully changed");
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "This batch does not exist in the system");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

