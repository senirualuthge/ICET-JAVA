    private void searchAndPopulate() {
        String batchNo = txtBatchNo.getText().trim();
        if (batchNo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Batch Number");
            return;
        }
        Batch batch = AccessBatchCollection.getInstance().getBatchCollection().searchBatch(batchNo);
        if (batch == null) {
            JOptionPane.showMessageDialog(this, "This batch does not exist in the system");
            return;
        }
        currentBatchNo = batch.getBatchNo();
        txtBatchNo.setText(batch.getBatchNo());
        cmbStatus.setSelectedIndex(batch.getStatus() == Batch.STATUS_OPEN ? 0 : 1);
        cmbStatus.setEnabled(true);
        btnUpdate.setEnabled(true);
    }

    private void clearForm() {
        currentBatchNo = null;
        txtBatchNo.setText("");
        cmbStatus.setSelectedIndex(0);
        cmbStatus.setEnabled(false);
        btnUpdate.setEnabled(false);
        txtBatchNo.requestFocusInWindow();
    }

