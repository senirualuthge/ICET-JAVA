    private void btnAddStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddStudentActionPerformed
        if (cmbBatch.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "Please select a batch");
            return;
        }
        String batchNo = (String) cmbBatch.getSelectedItem();
        Batch batch = AccessBatchCollection.getInstance().getBatchCollection().searchBatch(batchNo);
        
        if (batch == null) {
            JOptionPane.showMessageDialog(this, "This batch does not exist in the system");
            return;
        }
        if (batch.getStatus() == Batch.STATUS_CLOSED) {
            JOptionPane.showMessageDialog(this, "Enrollment for batch " + batchNo + " is CLOSED. Cannot add students.");
            return;
        }
        String nic = txtNic.getText().trim();
        if (nic.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIC cannot be empty");
            return;
        }
        String name = txtName.getText().trim();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name cannot be empty");
            return;
        }
        if (AccessStudentCollection.getInstance().getStudentCollection().searchStudentByNic(nic) != null) {
            Student existing = AccessStudentCollection.getInstance().getStudentCollection().searchStudentByNic(nic);
            JOptionPane.showMessageDialog(this,
                    "Student already added in the system\n\n"
                    + "Reg No: " + existing.getRegistrationNo() + "\n"
                    + "Name: " + existing.getName() + "\n"
                    + "NIC: " + existing.getNic() + "\n"
                    + "Batch: " + existing.getBatchNo());
            return;
        }
        boolean physical = cmbLectureMode.getSelectedIndex() == 0;
        String regNo = AccessStudentCollection.getInstance().getStudentCollection()
                .generateRegistrationNo(batchNo, physical);
        
        Student student = new Student(regNo, name, nic, batchNo,
                Student.MARK_NOT_CONDUCTED, Student.MARK_NOT_CONDUCTED);
        boolean isAdded = AccessStudentCollection.getInstance().getStudentCollection().addNewStudent(student);
        
        if (isAdded) {
            JOptionPane.showMessageDialog(this,
                    "Student added successfully\n\nStudent Registration No: " + regNo);
            txtNic.setText("");
            txtName.setText("");
            refreshRegNoPreview();
        } 
        else {
            JOptionPane.showMessageDialog(this, "Add Fail");
        }
    }//GEN-LAST:event_btnAddStudentActionPerformed

