    private void loadBatches() {
        cmbBatch.removeAllItems();
        Batch[] batches = AccessBatchCollection.getInstance().getBatchCollection().getAllBatch();
        int firstOpenIndex = -1;
        
        for (Batch batch : batches) {
            cmbBatch.addItem(batch.getBatchNo());
            if (firstOpenIndex == -1 && batch.getStatus() == Batch.STATUS_OPEN) {
                firstOpenIndex = cmbBatch.getItemCount() - 1;
            }
        }
        if (firstOpenIndex >= 0) {
            cmbBatch.setSelectedIndex(firstOpenIndex);
        }
        refreshRegNoPreview();
    }

    private void refreshRegNoPreview() {
        int index = cmbBatch.getSelectedIndex();
        if (index < 0) {
            txtRegNo.setText("");
            
            return;
        }
        String batchNo = (String) cmbBatch.getSelectedItem();
        
        boolean physical = cmbLectureMode.getSelectedIndex() == 0;
        
        txtRegNo.setText(AccessStudentCollection.getInstance().getStudentCollection()
                .generateRegistrationNo(batchNo, physical));
    }

