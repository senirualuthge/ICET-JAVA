    private void btnUpdateStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStudentActionPerformed
        if (currentRegistrationNo == null) {
            JOptionPane.showMessageDialog(this, "Please search a student first");
            return;
        }
        String name = txtName.getText().trim();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name cannot be empty");
            return;
        }
        String nic = txtNic.getText().trim();
        if (nic.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIC cannot be empty");
            return;
        }
        Student existing = AccessStudentCollection.getInstance().getStudentCollection().searchStudentByNic(nic);
        if (existing != null && !existing.getRegistrationNo().equalsIgnoreCase(currentRegistrationNo)) {
            JOptionPane.showMessageDialog(this, "NIC already exists in the system: " + nic);
            return;
        }
        boolean isUpdated = AccessStudentCollection.getInstance().getStudentCollection()
                .updateStudentDetails(currentRegistrationNo, name, nic);
        if (isUpdated) {
            JOptionPane.showMessageDialog(this, "Student updated successfully");
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "This student does not exist in the system");
        }
    }//GEN-LAST:event_btnUpdateStudentActionPerformed

