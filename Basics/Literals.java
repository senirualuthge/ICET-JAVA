import java.util.*;
class Literals{
	public static void main(String[] args){
		System.out.println(100);  //Integer Literals
		System.out.println(-123); //Integer Literals
		System.out.println(1.2345);//Floating point Literals
		System.out.println(0.0023);//Floating point Literals
		System.out.println('A'); //Character Literals
		System.out.println('7'); //Character Literals
		System.out.println(true); //Boolean Literals
		System.out.println(false);//Boolean Literals
		System.out.println("Niroth");//String Literals
		System.out.println("12345");//String Literals
		System.out.println("1.234");//String Literals
	}
}

