import java.util.*;
class Char2{
	public static void main(String args[]){
		char ch='A';
		System.out.println(ch+100); //165
		
		System.out.println('1'+100);//166
		System.out.println('A'+200);
		System.out.println("A"+200);
		System.out.println('B'+"100");//Concat-->B100
		System.out.println('\n'+0);
		System.out.println('\t'+0);
		System.out.println(' '+0);
		
	}
}

