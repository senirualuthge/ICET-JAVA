import java.util.*;
class Operators{
	public static void main(String args[]){
		int x=100,y=100,z=99;
		System.out.println(x>y); //true or false
		System.out.println(x==y);
		System.out.println(x!=y);
		System.out.println(x>y);
		System.out.println(x<y);
		System.out.println(x>=y);
		System.out.println(x<=y);
		System.out.println(x==z);
		System.out.println(x!=z);
		System.out.println(x>z);
		System.out.println(x<z);
		System.out.println(x<=z);
		System.out.println(x>=z);
	}
}
