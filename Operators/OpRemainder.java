import java.util.*;
class OpRemainder{
	public static void main(String args[]){
		
		System.out.println("17/6 : "+(17/6)); //2
		System.out.println("17%6 : "+(17%6)); //5
		System.out.println("17/7 : "+(17/7));	//2
		System.out.println("17%7 : "+(17%7));	//3
		
		System.out.println("17/17 : "+(17/17));	//1
		System.out.println("17%17 : "+(17%17));	//0
		
		System.out.println("17/27 : "+(17/27));	//0
		System.out.println("17%27 : "+(17%27));	//17

		
	}
}


